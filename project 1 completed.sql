--14.What are the categories for which average revenue is above the overall average. 

WITH CatRevenue AS (
    SELECT pci.prod_cat, AVG(t.total_amt) AS avg_revenue
    FROM Transactions t
    JOIN prod_cat_info pci ON t.prod_cat_code = pci.prod_cat_code
    WHERE t.Qty > 0
    GROUP BY pci.prod_cat
),
OverallAvg AS (
    SELECT AVG(total_amt) AS overall_avg FROM Transactions WHERE Qty > 0
)
SELECT cr.prod_cat, cr.avg_revenue
FROM CatRevenue cr, OverallAvg oa
WHERE cr.avg_revenue > oa.overall_avg

/*15. Find the average and total revenue by each subcategory for the categories which 
are among top 5 categories in terms of quantity sold.*/ 

WITH Top5Cats AS (
    SELECT TOP 5 pci.prod_cat
    FROM Transactions t
    JOIN prod_cat_info pci ON t.prod_cat_code = pci.prod_cat_code
    WHERE t.Qty > 0
    GROUP BY pci.prod_cat
    ORDER BY SUM(t.Qty) DESC
),
SubCatRevenue AS (
    SELECT 
        pci.prod_cat,
        pci.prod_subcat,
        SUM(t.total_amt) AS total_revenue,
        AVG(t.total_amt) AS avg_revenue,
        SUM(t.Qty) AS total_qty
    FROM Transactions t
    JOIN prod_cat_info pci ON t.prod_cat_code = pci.prod_cat_code
    WHERE t.Qty > 0 AND pci.prod_cat IN (SELECT prod_cat FROM Top5Cats)
    GROUP BY pci.prod_cat, pci.prod_subcat
)
SELECT prod_cat, prod_subcat, total_revenue, avg_revenue
FROM SubCatRevenue
ORDER BY prod_cat, total_revenue DESC