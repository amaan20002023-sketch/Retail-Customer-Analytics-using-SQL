/*10.What is percentage of sales and returns by product sub category; display only top 
5 sub categories in terms of sales?*/

WITH SalesReturns AS (
    SELECT 
        pci.prod_subcat,
        SUM(CASE WHEN t.Qty > 0 THEN t.total_amt ELSE 0 END) AS sales_amt,
        SUM(CASE WHEN t.Qty < 0 THEN ABS(t.total_amt) ELSE 0 END) AS return_amt
    FROM Transactions t
    JOIN prod_cat_info pci ON t.prod_cat_code = pci.prod_cat_code
    GROUP BY pci.prod_subcat
),
Totals AS (
    SELECT SUM(sales_amt) AS total_sales FROM SalesReturns
)
SELECT TOP 5
    sr.prod_subcat,
    sr.sales_amt,
    ROUND(100.0 * sr.sales_amt / t.total_sales, 2) AS sales_percentage,
    sr.return_amt,
    ROUND(100.0 * sr.return_amt / NULLIF(sr.sales_amt, 0), 2) AS return_percentage
FROM SalesReturns sr, Totals t
ORDER BY sr.sales_amt DESC;

/*11. For all customers aged between 25 to 35 years find what is the net total revenue 
generated by these consumers in last 30 days of transactions from max transaction 
date available in the data?*/ 

WITH AgeFiltered AS (
    SELECT customer_Id, DATEDIFF(YEAR, DOB, GETDATE()) AS age
    FROM Customer
    WHERE DATEDIFF(YEAR, DOB, GETDATE()) BETWEEN 25 AND 35
),
MaxDate AS (
    SELECT MAX(tran_date) AS max_tran_date FROM Transactions
),
Last30Days AS (
    SELECT t.*
    FROM Transactions t, MaxDate m
    WHERE t.tran_date >= DATEADD(DAY, -30, m.max_tran_date)
      AND t.Qty > 0
)
SELECT SUM(l.total_amt) AS net_revenue_last_30_days
FROM Last30Days l
JOIN AgeFiltered a ON l.cust_id = a.customer_Id;

/*12.Which product category has seen the max value of returns in the last 3 months of 
transactions? */

WITH Last3Months AS (
    SELECT t.*, pci.prod_cat
    FROM Transactions t
    JOIN prod_cat_info pci ON t.prod_cat_code = pci.prod_cat_code
    WHERE t.Qty < 0
      AND t.tran_date >= DATEADD(MONTH, -3, (SELECT MAX(tran_date) FROM Transactions))
)
SELECT TOP 1 prod_cat, SUM(ABS(total_amt)) AS return_value
FROM Last3Months
GROUP BY prod_cat
ORDER BY return_value DESC;

